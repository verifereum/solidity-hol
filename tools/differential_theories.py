"""Render disjoint HOL corpus wrappers from the maintained suite files."""

from pathlib import Path
from typing import Any
import json

HEADER = "(* Generated by tools/run_differential.py --write-theories. *)\n"
DIRECTORY = Path("tests/corpus")
YUL_DIRECTORY = Path("tests/yul-generated")


def theory_name(suite: str, side: str) -> str:
    prefixes = {"source": "solidityDifferentialCorpus_",
                "bytecode": "solidityBytecodeCorpus_", "yul": "yulDifferentialCorpus_"}
    return prefixes[side] + suite


def results_path(theory: str) -> Path:
    """The declared verdict output of a source or Yul suite theory."""
    directory = YUL_DIRECTORY if theory.startswith("yul") else DIRECTORY
    return directory / (theory.removesuffix("Theory") + ".results.jsonl")


def suite_files(root: Path, corpus_path: Path, corpus: dict[str, Any]) -> dict[str, Path]:
    directory = root / corpus_path.parent / corpus["suite_directory"]
    return {json.loads(path.read_text(encoding="utf-8"))["name"]: path.relative_to(root)
            for path in sorted(directory.glob("*.json"))}


def fixture_files(root: Path, suite: dict[str, Any], *, sources: bool) -> set[Path]:
    paths = set()
    for contract in [suite] + ([suite["peer"]] if "peer" in suite else []):
        path = Path(contract["artifact"])
        paths.add(path)
        if sources:
            artifact = json.loads((root / path).read_text(encoding="utf-8"))
            paths.update(Path(name) for name in artifact["input"]["sources"])
            if "unoptimizedFailure" in artifact:
                paths.add(Path("profiles/solc-0.8.37-via-ir-osaka-optimized.json"))
    if sources:
        paths.update([Path("SOLIDITY_PIN"), Path("profiles/solc-0.8.37-via-ir-osaka.json")])
    return paths


def wrapper(root: Path, suite: dict[str, Any], path: Path, fuel: int,
            side: str) -> tuple[Path, str]:
    name = theory_name(suite["name"], side)
    bytecode = theory_name(suite["name"], "bytecode")
    deps = fixture_files(root, suite, sources=side != "bytecode") | {path}
    if side == "bytecode":
        ancestors, library = "solidityBytecode", "solidityBytecodeLib"
        call = (f'  {{root = "../..", suite_file = "{path.as_posix()}"}}\n')
        entry = "run_suite_file"
    elif side == "source":
        ancestors, library = f"solidityDifferential {bytecode}", "solidityDifferentialLib"
        call = (f'  {{root = "../..", suite_file = "{path.as_posix()}",\n'
                f'   fuel = {fuel}, bytecode_theory = "{bytecode}"}}\n')
        entry = "run_suite_file"
    else:
        ancestors = "solidityDifferential yulAST yulState yulEvaluator yulDifferential"
        library, entry = "solidityDifferentialLib", "run_yul_suite_file"
        deps.update(Path(f"testdata/yul/generated/{suite['name']}.{stage}.json")
                    for stage in ("ir", "optimized"))
        call = (f'  {{root = "../..", suite_file = "{path.as_posix()}",\n'
                '   yul_root = "../../testdata/yul/generated"}\n')
    text = (HEADER + f"Theory {name}\nAncestors {ancestors}\nLibs {library}\n\n"
            "fun holbuild_extra_deps (_ : string list) = ()\n"
            "val () = holbuild_extra_deps [\n" +
            ",\n".join(f'  "../../{p.as_posix()}"' for p in sorted(deps)) +
            "\n]\n")
    if side == "bytecode":
        text += f"val () = {library}.{entry}\n" + call
    else:
        output = results_path(name + "Theory").name
        text += ('fun holbuild_extra_outputs (_ : string list) = ()\n'
                 f'val () = holbuild_extra_outputs ["{output}"]\n'
                 f'val () = {library}.with_results "{output}" (fn () =>\n'
                 f'  {library}.{entry}\n' + call.rstrip() + ")\n")
    directory = YUL_DIRECTORY if side == "yul" else DIRECTORY
    return directory / f"{name}Script.sml", text


def wrappers(root: Path, corpus_path: Path, corpus: dict[str, Any], *,
             yul: bool = False) -> dict[Path, str]:
    paths = suite_files(root, corpus_path, corpus)
    result = {}
    for suite in corpus["suites"]:
        for side in (["yul"] if yul else ["bytecode", "source"]):
            path, text = wrapper(root, suite, paths[suite["name"]],
                                 suite.get("fuel", corpus["fuel"]), side)
            result[path] = text
    return result


def write_wrappers(root: Path, expected: dict[Path, str]) -> None:
    for path, text in expected.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")


def refresh_rollup(root: Path, corpus: dict[str, Any]) -> None:
    text = ("(* Compatibility roll-up; refreshed with the integration reports. *)\n"
            "Theory solidityDifferentialCorpus\nAncestors\n" +
            "\n".join("  " + theory_name(suite["name"], "source")
                       for suite in corpus["suites"]) + "\n")
    (root / "tests/solidityDifferentialCorpusScript.sml").write_text(text, encoding="utf-8")
